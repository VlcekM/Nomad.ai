using System.Text.Json;
using System.Text.Json.Serialization;
using Klodi.Core.Protocol;

namespace Klodi.Core.Sessions;

/// <summary>
/// One line of a session transcript (<c>~/.claude/projects/&lt;folder&gt;/&lt;session&gt;.jsonl</c>). One flat
/// shape covers all record types (user, assistant, system, summary, custom-title, …); unknown fields
/// are ignored.
/// </summary>
public sealed class TranscriptRecord
{
    [JsonPropertyName("type")] public string? Type { get; set; }
    [JsonPropertyName("subtype")] public string? Subtype { get; set; }
    [JsonPropertyName("uuid")] public string? Uuid { get; set; }
    [JsonPropertyName("parentUuid")] public string? ParentUuid { get; set; }
    [JsonPropertyName("logicalParentUuid")] public string? LogicalParentUuid { get; set; }
    [JsonPropertyName("sessionId")] public string? SessionId { get; set; }
    [JsonPropertyName("cwd")] public string? Cwd { get; set; }
    [JsonPropertyName("timestamp")] public string? Timestamp { get; set; }
    [JsonPropertyName("isSidechain")] public bool? IsSidechain { get; set; }
    [JsonPropertyName("isMeta")] public bool? IsMeta { get; set; }
    [JsonPropertyName("isCompactSummary")] public bool? IsCompactSummary { get; set; }
    [JsonPropertyName("permissionMode")] public string? PermissionMode { get; set; }
    [JsonPropertyName("message")] public WireMessage? Message { get; set; }
    [JsonPropertyName("toolUseResult")] public JsonElement ToolUseResult { get; set; }
    [JsonPropertyName("customTitle")] public string? CustomTitle { get; set; }

    /// <summary>Title generated by the CLI (<c>generate_session_title</c>), record type <c>ai-title</c>.</summary>
    [JsonPropertyName("aiTitle")] public string? AiTitle { get; set; }
    [JsonPropertyName("summary")] public string? Summary { get; set; }
    [JsonPropertyName("content")] public JsonElement Content { get; set; }

    public bool IsConversationRecord => Type is "user" or "assistant";

    public static TranscriptRecord? Parse(string line)
    {
        if (string.IsNullOrWhiteSpace(line) || line[0] != '{')
        {
            return null;
        }

        try
        {
            return JsonSerializer.Deserialize(line, SessionJsonContext.Default.TranscriptRecord);
        }
        catch (JsonException)
        {
            return null;
        }
    }
}

[JsonSourceGenerationOptions(NumberHandling = JsonNumberHandling.AllowReadingFromString)]
[JsonSerializable(typeof(TranscriptRecord))]
internal sealed partial class SessionJsonContext : JsonSerializerContext;
